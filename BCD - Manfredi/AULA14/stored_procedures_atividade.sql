-- 5. consultar_estoque(IN p_id_produto INT) usando variável local

DELIMITER $$

CREATE PROCEDURE CONSULTAR_ESTOQUE(IN P_ID_PRODUTO INT)
BEGIN
    DECLARE V_QUANTIDADE INT;

    SELECT QUANTIDADE
    INTO V_QUANTIDADE
    FROM ESTOQUE
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    IF V_QUANTIDADE IS NULL THEN
        SELECT 'PRODUTO SEM REGISTRO DE ESTOQUE' AS MENSAGEM;
    ELSE
        SELECT V_QUANTIDADE AS QUANTIDADE_EM_ESTOQUE;
    END IF;
END $$

DELIMITER ;

CALL CONSULTAR_ESTOQUE(1);

