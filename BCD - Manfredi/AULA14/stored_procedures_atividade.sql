-- 8. alterar_preco(...) impedindo valor <= 0

DELIMITER $$

CREATE PROCEDURE ATUALIZAR_PRECO_PRODUTOS (
    IN P_ID_PRODUTO INT,
    IN P_NOVO_PRECO DECIMAL (10,2)
)
BEGIN
    IF P_NOVO_PRECO > 0 THEN
        UPDATE PRODUTO 
        SET PRECO = P_NOVO_PRECO
        WHERE ID_PRODUTO = P_ID_PRODUTO;

        SELECT 'PRECO ATUALIZADO' AS MENSAGEM;
    ELSE
        SELECT 'PRECO INVALIDO' AS MENSAGEM;
    END IF;
END $$

DELIMITER ;

CALL ATUALIZAR_PRECO_PRODUTOS(2,10);


-- 9. criar_pedido(IN p_id_cliente INT, OUT p_id_pedido INT)

DELIMITER $$

CREATE PROCEDURE CRIAR_PEDIDO(
    IN P_ID_CLIENTE INT,
    OUT P_ID_PEDIDO INT
)
BEGIN
    START TRANSACTION;

    INSERT INTO PEDIDO (
        ID_CLIENTE,
        DATA_PEDIDO,
        STATUS_PEDIDO
    )
    VALUES (
        P_ID_CLIENTE,
        NOW(),
        'ABERTO'
    );

    SET P_ID_PEDIDO = LAST_INSERT_ID();
    COMMIT;
END $$

DELIMITER ;

