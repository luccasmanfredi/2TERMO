-- 2. buscar_produto_por_nome(IN p_busca VARCHAR(100))

DELIMITER $$

CREATE PROCEDURE BUSCAR_PRODUTO_POR_NOME(IN P_BUSCA VARCHAR(100))
BEGIN
    SELECT ID_PRODUTO, NOME, PRECO
    FROM PRODUTO
    WHERE ATIVO = TRUE
      AND NOME LIKE CONCAT('%', P_BUSCA, '%')
    ORDER BY NOME;
END $$

DELIMITER ;

